//! The Agent Skill that ships inside the binary: `seedwell skill show | install | uninstall`.
//!
//! The text is generated from the command table (`help::COMMANDS`), the same table the parser's tests
//! walk, so a command in the skill exists and an example in the skill parses. Nothing is written
//! anywhere until the user runs `skill install`.
#![allow(missing_docs)] // variant fields are named after the options they hold


use std::io::{BufRead, IsTerminal, Write};
use std::path::{Path, PathBuf};

use serde_json::json;

use crate::args::{Opts, Usage};
use crate::commands::{CliError, Global, R, show};
use crate::help::{AGENTS_HEAD, AGENTS_RECIPES, CHAT_GUIDE, COMMANDS, EXIT_CODES, MAIL_GUIDE, UNITS};

/// A `skill` subcommand.
#[derive(Clone, Debug, PartialEq)]
pub enum Cmd {
    /// Print SKILL.md and the reference.
    Show,
    /// Write the files.
    Install {
        /// Target directory (default `~/.claude/skills/seedwell`).
        dir: Option<PathBuf>,
        /// Replace modified files without asking.
        force: bool,
    },
    /// Remove the files.
    Uninstall {
        /// Directory the skill was installed to.
        dir: Option<PathBuf>,
    },
}

/// Words after `skill`.
pub fn parse(args: Vec<String>) -> Result<Cmd, Usage> {
    let mut it = args.into_iter();
    let sub = it.next().ok_or_else(|| Usage("usage: seedwell skill show | install [--dir PATH] [--force] | uninstall [--dir PATH]".into()))?;
    let mut o = Opts::new(it.collect());
    let dir = o.value(&["--dir"])?.map(PathBuf::from);
    let force = o.flag(&["--force", "-f"]);
    let pos = o.finish()?;
    if let Some(x) = pos.first() {
        return Err(Usage(format!("unexpected argument `{x}`")));
    }
    match sub.as_str() {
        "show" if dir.is_none() && !force => Ok(Cmd::Show),
        "install" => Ok(Cmd::Install { dir, force }),
        "uninstall" if !force => Ok(Cmd::Uninstall { dir }),
        _ => Err(Usage("usage: seedwell skill show | install [--dir PATH] [--force] | uninstall [--dir PATH]".into())),
    }
}

/// The file names of the skill.
pub const FILES: [&str; 2] = ["SKILL.md", "REFERENCE.md"];
const MANIFEST: &str = ".seedwell-skill";

/// SKILL.md: frontmatter, rules and recipes.
pub fn skill_md() -> String {
    format!(
        "---\nname: seedwell\ndescription: Control and debug the Seedwell BitTorrent client from the terminal with the `seedwell` command. Use when the user asks to add, list, pause, resume, remove or watch torrents and downloads, choose files, set speed limits, check why a download is slow or stuck (trackers, peers, ports), test with simulated torrents, sync folders, or work with agents of other projects and other computers through Seedwell: mail between projects (`seedwell mail inbox|send|reply|done|watch`, an inbox per project, items open until closed with a status) and chat channels.\n---\n\n\
# Seedwell\n\n{AGENTS_HEAD}\n{AGENTS_RECIPES}\n\
## Mail\n\n```\n{MAIL_GUIDE}```\n\n\
## Chat and mail\n\n```\n{CHAT_GUIDE}```\n\n\
See REFERENCE.md in this folder for every command, its JSON shape and examples. `seedwell help agents` prints the same guide.\n\n\
<!-- generated by seedwell {} -->\n",
        env!("CARGO_PKG_VERSION")
    )
}

/// REFERENCE.md: commands, JSON shapes, examples, units and exit codes, from the command table.
pub fn reference_md() -> String {
    let mut o = String::from("# Seedwell command reference\n\nEvery command takes `--json`. Every JSON object has `\"v\":1`.\n\n## Commands\n\n");
    let mut group = "";
    for c in COMMANDS {
        if c.group != group {
            o.push_str(&format!("### {}\n\n", c.group));
            group = c.group;
        }
        o.push_str(&format!("#### seedwell {}\n\n{} (needs: {})\n\n", c.name, c.summary, c.needs));
        o.push_str(&format!("    seedwell {}\n\n", c.usage.replace('\n', "\n    ")));
        if !c.details.is_empty() {
            o.push_str(&format!("{}\n\n", c.details));
        }
        if !c.examples.is_empty() {
            o.push_str("Examples:\n\n");
            for e in c.examples {
                o.push_str(&format!("    {e}\n"));
            }
            o.push('\n');
        }
        o.push_str(&format!("JSON: `{}`\n\n", c.json));
    }
    o.push_str(&format!("## Units\n\n{UNITS}\n\n## Exit codes\n\n{EXIT_CODES}\n\n<!-- generated by seedwell {} -->\n", env!("CARGO_PKG_VERSION")));
    o
}

/// `(file name, content)` of everything that gets installed.
pub fn files() -> Vec<(&'static str, String)> {
    vec![(FILES[0], skill_md()), (FILES[1], reference_md())]
}

/// `~/.claude/skills/seedwell` for a given home directory.
pub fn default_dir(home: &Path) -> PathBuf {
    home.join(".claude").join("skills").join("seedwell")
}

fn target(dir: Option<PathBuf>) -> Result<PathBuf, CliError> {
    match dir {
        Some(d) => Ok(d),
        None => {
            let home = std::env::var_os("HOME").filter(|h| !h.is_empty()).ok_or_else(|| CliError::plain(1, "HOME is not set; give --dir PATH"))?;
            Ok(default_dir(Path::new(&home)))
        }
    }
}

/// A small, stable hash to notice local edits (not a security measure).
fn fnv(s: &str) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in s.bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    h
}

fn manifest_hashes(dir: &Path) -> std::collections::HashMap<String, u64> {
    std::fs::read_to_string(dir.join(MANIFEST))
        .ok()
        .and_then(|t| serde_json::from_str::<std::collections::HashMap<String, u64>>(&t).ok())
        .unwrap_or_default()
}

/// Run `skill …`.
pub fn run(cmd: Cmd, g: &Global) -> R {
    match cmd {
        Cmd::Show => {
            let f = files();
            if g.json {
                let v = json!({ "files": f.iter().map(|(n, c)| json!({"name": n, "content": c})).collect::<Vec<_>>() });
                show(g, &v, String::new);
            } else {
                print!("{}\n\n--- REFERENCE.md ---\n\n{}", f[0].1, f[1].1);
            }
            Ok(())
        }
        Cmd::Install { dir, force } => {
            let dir = target(dir)?;
            let results = install(&dir, force, &mut |path| ask_replace(path))?;
            let v = json!({ "action": "installed", "path": dir, "files": results.iter().map(|(n, s)| json!({"name": n, "status": s})).collect::<Vec<_>>() });
            show(g, &v, || {
                let mut s = format!("Seedwell skill for Claude Code: {}\n", dir.display());
                for (n, st) in &results {
                    s.push_str(&format!("  {n}: {st}\n"));
                }
                s.push_str("Claude Code picks it up in new sessions. Remove it with `seedwell skill uninstall`.");
                s
            });
            Ok(())
        }
        Cmd::Uninstall { dir } => {
            let dir = target(dir)?;
            let removed = uninstall(&dir)?;
            let v = json!({ "action": "uninstalled", "path": dir, "files": removed });
            show(g, &v, || if removed.is_empty() { format!("Nothing to remove in {}", dir.display()) } else { format!("Removed {} from {}", removed.join(", "), dir.display()) });
            Ok(())
        }
    }
}

fn ask_replace(path: &Path) -> bool {
    if !std::io::stdin().is_terminal() {
        return false;
    }
    eprint!("{} was changed since it was installed. Replace it? [y/N] ", path.display());
    let _ = std::io::stderr().flush();
    let mut line = String::new();
    let _ = std::io::stdin().lock().read_line(&mut line);
    matches!(line.trim().to_ascii_lowercase().as_str(), "y" | "yes")
}

/// Write the skill into `dir`. A file that differs from what Seedwell wrote before (or that Seedwell did
/// not write) is only replaced with `force` or when `confirm` says yes. Returns `(name, status)`.
pub fn install(dir: &Path, force: bool, confirm: &mut dyn FnMut(&Path) -> bool) -> Result<Vec<(String, &'static str)>, CliError> {
    let io = |e: std::io::Error| CliError::plain(1, format!("cannot write {}: {e}", dir.display()));
    std::fs::create_dir_all(dir).map_err(io)?;
    let known = manifest_hashes(dir);
    let mut hashes = known.clone();
    let mut out = Vec::new();
    let mut refused = Vec::new();
    for (name, content) in files() {
        let path = dir.join(name);
        let status = match std::fs::read_to_string(&path) {
            Err(_) => {
                std::fs::write(&path, &content).map_err(io)?;
                "written"
            }
            Ok(old) if old == content => "unchanged",
            Ok(old) => {
                let ours_unmodified = known.get(name).is_some_and(|h| *h == fnv(&old));
                if force || ours_unmodified || confirm(&path) {
                    std::fs::write(&path, &content).map_err(io)?;
                    "replaced"
                } else {
                    refused.push(name);
                    "kept (modified; use --force to replace)"
                }
            }
        };
        if !status.starts_with("kept") {
            hashes.insert(name.to_owned(), fnv(&content));
        }
        out.push((name.to_owned(), status));
    }
    std::fs::write(dir.join(MANIFEST), serde_json::to_string(&hashes).unwrap_or_default()).map_err(io)?;
    if !refused.is_empty() {
        let mut e = CliError::plain(1, format!("{} was modified and left alone; run again with --force to replace it", refused.join(", ")));
        e.data = Some(json!({ "files": out.iter().map(|(n, s)| json!({"name": n, "status": s})).collect::<Vec<_>>() }));
        return Err(e);
    }
    Ok(out)
}

/// Remove the skill's files from `dir`, and the folder when nothing else is in it. Returns the removed names.
pub fn uninstall(dir: &Path) -> Result<Vec<String>, CliError> {
    let mut removed = Vec::new();
    for name in FILES.iter().copied().chain([MANIFEST]) {
        let p = dir.join(name);
        if p.is_file() {
            std::fs::remove_file(&p).map_err(|e| CliError::plain(1, format!("cannot remove {}: {e}", p.display())))?;
            removed.push(name.to_owned());
        }
    }
    let _ = std::fs::remove_dir(dir);
    Ok(removed)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cmd::{parse as parse_cmd, shell_words};

    /// Every `seedwell …` line of the skill text, split into commands, with placeholders filled in.
    fn commands_in(text: &str) -> Vec<String> {
        let sample = [("<torrent>", "sintel"), ("<sim>", "sim1"), ("<id>", "3f2a9c"), ("<favorite>", "tl"), ("<token>", "tok"), ("<tracker>", "tl")];
        let mut out = Vec::new();
        for line in text.lines() {
            let t = line.trim();
            if !t.contains("seedwell ") || t.starts_with("seedwell ") && t.contains(" - ") {
                continue;
            }
            for part in t.split("   ").flat_map(|p| p.split(" | ")).flat_map(|p| p.split(" then ")) {
                let mut p = part.trim().trim_start_matches('(').trim_end_matches(')').trim().to_owned();
                if !p.starts_with("seedwell ") || p.contains('[') || p.contains('|') || p.contains("...") || p.contains('`') {
                    continue;
                }
                for (k, v) in sample {
                    p = p.replace(k, v);
                }
                if p.contains('<') {
                    continue;
                }
                out.push(p);
            }
        }
        out
    }

    #[test]
    fn frontmatter_is_valid() {
        let s = skill_md();
        assert!(s.starts_with("---\nname: seedwell\ndescription: "), "{s}");
        let end = s[4..].find("\n---\n").expect("frontmatter closes");
        let fm = &s[4..4 + end];
        assert_eq!(fm.lines().count(), 2, "name and description only");
        assert!(fm.contains("Use when"), "the description says when to use it");
    }

    #[test]
    fn every_command_in_the_skill_exists_and_every_example_parses() {
        let mut checked = 0;
        for (name, text) in files() {
            for cmdline in commands_in(&text) {
                let mut w = shell_words(&cmdline);
                w.remove(0);
                w.retain(|a| a != "--json");
                if let Err(u) = parse_cmd(w) {
                    panic!("{name}: `{cmdline}` does not parse: {u}");
                }
                checked += 1;
            }
        }
        assert!(checked > 60, "the skill shows plenty of examples ({checked})");
    }

    #[test]
    fn every_command_of_the_cli_is_in_the_reference() {
        let r = reference_md();
        for c in COMMANDS {
            assert!(r.contains(&format!("#### seedwell {}", c.name)), "{} missing from the reference", c.name);
        }
    }

    #[test]
    fn install_asks_before_replacing_a_modified_file_and_uninstall_removes() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("skills").join("seedwell");
        let r = install(&dir, false, &mut |_| panic!("nothing to ask on a fresh install")).unwrap();
        assert!(r.iter().all(|(_, s)| *s == "written"));
        assert!(dir.join("SKILL.md").is_file() && dir.join("REFERENCE.md").is_file());
        // Again: unchanged.
        let r = install(&dir, false, &mut |_| panic!("unchanged files need no question")).unwrap();
        assert!(r.iter().all(|(_, s)| *s == "unchanged"));
        // The user edits SKILL.md: asked; "no" keeps it.
        std::fs::write(dir.join("SKILL.md"), "my notes").unwrap();
        let mut asked = 0;
        let e = install(&dir, false, &mut |_| {
            asked += 1;
            false
        })
        .unwrap_err();
        assert_eq!(asked, 1);
        assert!(e.message.contains("--force"));
        assert_eq!(std::fs::read_to_string(dir.join("SKILL.md")).unwrap(), "my notes");
        // "yes" replaces, --force replaces without asking.
        install(&dir, false, &mut |_| true).unwrap();
        assert!(std::fs::read_to_string(dir.join("SKILL.md")).unwrap().starts_with("---\nname: seedwell"));
        std::fs::write(dir.join("SKILL.md"), "my notes again").unwrap();
        install(&dir, true, &mut |_| panic!("--force never asks")).unwrap();
        assert!(std::fs::read_to_string(dir.join("SKILL.md")).unwrap().starts_with("---\nname: seedwell"));
        let removed = uninstall(&dir).unwrap();
        assert!(removed.contains(&"SKILL.md".to_owned()));
        assert!(!dir.exists(), "the empty folder goes too");
    }

    #[test]
    fn default_dir_is_under_home_claude_skills() {
        assert_eq!(default_dir(Path::new("/home/x")), Path::new("/home/x/.claude/skills/seedwell"));
    }

    #[test]
    fn parses() {
        assert_eq!(parse(vec!["show".into()]).unwrap(), Cmd::Show);
        assert!(matches!(parse(vec!["install".into(), "--dir".into(), "/x".into(), "--force".into()]).unwrap(), Cmd::Install { force: true, dir: Some(_) }));
        assert!(parse(vec!["uninstall".into(), "--force".into()]).is_err());
        assert!(parse(vec![]).is_err());
    }
}
